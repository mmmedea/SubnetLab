-- Original bigint-keyed SubnetLab schema. Kept for the legacy Express/custom-JWT app.
create table public.users (
  id bigint generated by default as identity primary key,
  email text not null,
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table public.plans (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  name text not null,
  family smallint not null check (family in (4,6)),
  base text not null,
  data_json text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.ip_records (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  plan_id bigint not null references public.plans(id) on delete cascade,
  network_cidr text not null,
  family smallint not null check (family in (4,6)),
  address text not null,
  address_int numeric not null,
  label text not null,
  status text not null default 'active' check (status in ('active','released')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.reservations (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  plan_id bigint not null references public.plans(id) on delete cascade,
  network_cidr text not null,
  family smallint not null check (family in (4,6)),
  address text not null,
  address_int numeric not null,
  label text not null,
  mac text not null,
  created_at timestamptz not null default now()
);

create table public.practice_questions (
  id uuid primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  topic text not null,
  difficulty text not null,
  prompt text not null,
  answer text not null,
  explanation text not null,
  created_at timestamptz not null default now()
);

create table public.attempts (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  question_id uuid not null,
  topic text not null,
  difficulty text not null,
  correct boolean not null,
  created_at timestamptz not null default now()
);

-- These early indexes are replaced or retained by later hardening migrations.
create index plans_user_updated_idx on public.plans(user_id,updated_at desc);
create index ip_records_user_plan_idx on public.ip_records(user_id,plan_id);
create index reservations_user_plan_idx on public.reservations(user_id,plan_id);
create index attempts_user_time on public.attempts(user_id,created_at desc);
create index practice_questions_user_id_idx on public.practice_questions(user_id);
create unique index ip_active_unique on public.ip_records(user_id,address_int) where status='active';
create unique index reservation_unique on public.reservations(user_id,address_int);
